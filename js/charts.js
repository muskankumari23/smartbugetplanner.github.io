/**
 * Chart Initialization and Update Logic using Chart.js
 */

let costPieChartInstance = null;
let valueBarChartInstance = null;

function renderCharts(selectedItems, totalBudget, totalCost) {
  const pieCanvas = document.getElementById('cost-pie-chart');
  const barCanvas = document.getElementById('value-bar-chart');
  
  if (!pieCanvas || !barCanvas) return;

  // Pie Chart: Budget Breakdown
  const remainingBudget = totalBudget - totalCost;
  
  // Aggregate cost by category for selected items
  const categoryCosts = {};
  selectedItems.forEach(item => {
    categoryCosts[item.category] = (categoryCosts[item.category] || 0) + item.cost;
  });

  const pieLabels = [...Object.keys(categoryCosts), 'Remaining Budget'];
  const pieData = [...Object.values(categoryCosts), remainingBudget];
  const pieColors = [
    '#4f46e5', // Primary
    '#0ea5e9', // Secondary
    '#10b981', // Success
    '#f59e0b', // Warning
    '#8b5cf6', // Purple
    '#e2e8f0'  // Remaining (gray)
  ];

  if (costPieChartInstance) costPieChartInstance.destroy();
  
  costPieChartInstance = new Chart(pieCanvas, {
    type: 'doughnut',
    data: {
      labels: pieLabels,
      datasets: [{
        data: pieData,
        backgroundColor: pieColors,
        borderWidth: 0,
        hoverOffset: 4
      }]
    },
    options: {
      responsive: true,
      maintainAspectRatio: false,
      plugins: {
        legend: {
          position: 'right',
          labels: {
            color: document.body.classList.contains('dark-mode') ? '#f8fafc' : '#1e293b'
          }
        }
      }
    }
  });

  // Bar Chart: Value generated by category
  const categoryValues = {};
  selectedItems.forEach(item => {
    categoryValues[item.category] = (categoryValues[item.category] || 0) + item.value;
  });

  if (valueBarChartInstance) valueBarChartInstance.destroy();
  
  valueBarChartInstance = new Chart(barCanvas, {
    type: 'bar',
    data: {
      labels: Object.keys(categoryValues),
      datasets: [{
        label: 'Total Value',
        data: Object.values(categoryValues),
        backgroundColor: 'rgba(79, 70, 229, 0.8)',
        borderRadius: 6
      }]
    },
    options: {
      responsive: true,
      maintainAspectRatio: false,
      scales: {
        y: {
          beginAtZero: true,
          grid: {
            color: document.body.classList.contains('dark-mode') ? 'rgba(255,255,255,0.1)' : 'rgba(0,0,0,0.1)'
          },
          ticks: {
            color: document.body.classList.contains('dark-mode') ? '#f8fafc' : '#1e293b'
          }
        },
        x: {
          grid: { display: false },
          ticks: {
            color: document.body.classList.contains('dark-mode') ? '#f8fafc' : '#1e293b'
          }
        }
      },
      plugins: {
        legend: { display: false }
      }
    }
  });
}
